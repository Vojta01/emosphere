#!/usr/bin/env python3
"""EmoSphere brand assets — refined "nebula planet" master (v4).

Refinements applied (see /root/workspace/noc/emosphere-icon-choice.txt):
  1. Simplified for small sizes: no meridian grid, single equator line,
     strong planet rim (white+indigo, 2 strokes) instead of a faint outline.
  2. Dot hierarchy: joy (largest, 62) -> tired (smallest, 27); one consistent
     light direction from the top-left across every element (background glow,
     sphere shading, nebula highlight, dot glow, dot highlight + specular).
  3. Nebula fill limited to 5 emotion colours with soft gradients.

Palette (emotions): joy #FFD93D · calm #4ADE80 · love #F472B6 · surprise #FB923C
                    sad #60A5FA · anger #EF4444 · fear #A78BFA · tired #94A3B8
Background: #0B1020 -> #0E1430, accent #6366F1.

Writes only SVG sources into this directory. Rasterize with render_icons.sh
(rsvg-convert).
"""

from pathlib import Path

OUT = Path(__file__).resolve().parent

COLORS = {
    "joy": "#FFD93D",
    "calm": "#4ADE80",
    "love": "#F472B6",
    "surprise": "#FB923C",
    "sad": "#60A5FA",
    "anger": "#EF4444",
    "fear": "#A78BFA",
    "tired": "#94A3B8",
}

# (slug, cx, cy, r) - deliberately ordered by size: a clear visual hierarchy.
DOTS = [
    ("joy", 500, 300, 62),
    ("love", 688, 430, 50),
    ("calm", 505, 718, 46),
    ("surprise", 652, 612, 42),
    ("sad", 352, 640, 40),
    ("anger", 300, 430, 36),
    ("fear", 400, 350, 32),
    ("tired", 592, 500, 27),
]

# Nebula fill: exactly 5 emotion colours, soft transitions.
NEBULA = [
    ("joy", 440, 372, 216, 0.34),
    ("love", 656, 470, 210, 0.30),
    ("sad", 470, 664, 230, 0.30),
    ("calm", 368, 568, 182, 0.26),
    ("fear", 600, 596, 172, 0.22),
]

NOTE = "<!-- EmoSphere brand asset - generated by generate_icons.py - do not hand-edit -->"


def _defs() -> str:
    p = [
        # Background: #0B1020 -> #0E1430 family, brighter toward the top-left light source.
        '<radialGradient id="bg" cx="28%" cy="22%" r="102%">'
        '<stop offset="0%" stop-color="#16204A"/><stop offset="42%" stop-color="#0E1430"/>'
        '<stop offset="100%" stop-color="#0B1020"/></radialGradient>',
        # Indigo accent halo, nudged toward the top-left light source.
        '<radialGradient id="halo" cx="47%" cy="45%" r="52%">'
        '<stop offset="0%" stop-color="#6366F1" stop-opacity="0.34"/>'
        '<stop offset="100%" stop-color="#6366F1" stop-opacity="0"/></radialGradient>',
        # Sphere: lit from the top-left.
        '<radialGradient id="sph" cx="34%" cy="28%" r="84%">'
        '<stop offset="0%" stop-color="#3E63B4"/><stop offset="45%" stop-color="#1B2E63"/>'
        '<stop offset="100%" stop-color="#0B1330"/></radialGradient>',
        # Rim: bright at the top-left, fading to indigo at the bottom-right.
        '<linearGradient id="rim" x1="230" y1="230" x2="800" y2="810" gradientUnits="userSpaceOnUse">'
        '<stop offset="0%" stop-color="#FFFFFF" stop-opacity="0.55"/>'
        '<stop offset="50%" stop-color="#FFFFFF" stop-opacity="0.22"/>'
        '<stop offset="100%" stop-color="#A9B6F0" stop-opacity="0.16"/></linearGradient>',
        '<radialGradient id="dotlight" cx="30%" cy="26%" r="80%">'
        '<stop offset="0%" stop-color="#FFFFFF" stop-opacity="0.42"/>'
        '<stop offset="55%" stop-color="#FFFFFF" stop-opacity="0.07"/>'
        '<stop offset="100%" stop-color="#FFFFFF" stop-opacity="0"/></radialGradient>',
        '<radialGradient id="spechilite">'
        '<stop offset="0%" stop-color="#FFFFFF" stop-opacity="0.10"/>'
        '<stop offset="100%" stop-color="#FFFFFF" stop-opacity="0"/></radialGradient>',
        '<linearGradient id="wm" x1="0" y1="0" x2="0" y2="1">'
        '<stop offset="0%" stop-color="#FFFFFF"/><stop offset="100%" stop-color="#AEB9FF"/></linearGradient>',
        '<clipPath id="clip"><circle cx="512" cy="512" r="310"/></clipPath>',
    ]
    for slug, _, _, _, op in NEBULA:
        c = COLORS[slug]
        p.append(
            f'<radialGradient id="neb_{slug}"><stop offset="0%" stop-color="{c}" stop-opacity="{op}"/>'
            f'<stop offset="100%" stop-color="{c}" stop-opacity="0"/></radialGradient>'
        )
    for slug, c in COLORS.items():
        # Dot glow: same top-left bias so every dot is lit from one direction.
        p.append(
            f'<radialGradient id="glow_{slug}" cx="35%" cy="30%" r="72%">'
            f'<stop offset="0%" stop-color="{c}" stop-opacity="0.50"/>'
            f'<stop offset="100%" stop-color="{c}" stop-opacity="0"/></radialGradient>'
        )
    return "<defs>" + "".join(p) + "</defs>"


def _planet(scale: float = 1.0, cx: float = 512, cy: float = 512) -> str:
    inner = ['<circle cx="512" cy="512" r="310" fill="url(#sph)"/>']
    for slug, x, y, r, _op in NEBULA:
        inner.append(f'<circle cx="{x}" cy="{y}" r="{r}" fill="url(#neb_{slug})"/>')
    # A single, subtle equator line (grid simplified for small sizes).
    inner.append(
        '<ellipse cx="512" cy="512" rx="310" ry="112" fill="none" '
        'stroke="#FFFFFF" stroke-opacity="0.14" stroke-width="3"/>'
    )
    # Specular sheen on the top-left of the sphere.
    inner.append(
        '<ellipse cx="416" cy="352" rx="188" ry="112" fill="url(#spechilite)" '
        'transform="rotate(-28 416 352)"/>'
    )
    for slug, x, y, r in DOTS:
        c = COLORS[slug]
        inner.append(f'<circle cx="{x}" cy="{y}" r="{r * 1.62:.0f}" fill="url(#glow_{slug})"/>')
        inner.append(f'<circle cx="{x}" cy="{y}" r="{r}" fill="{c}"/>')
        inner.append(f'<circle cx="{x}" cy="{y}" r="{r}" fill="url(#dotlight)"/>')
        inner.append(
            f'<circle cx="{x - r * 0.30:.0f}" cy="{y - r * 0.30:.0f}" r="{r * 0.20:.1f}" '
            'fill="#FFFFFF" opacity="0.72"/>'
        )
    body = f'<g clip-path="url(#clip)">{"".join(inner)}</g>'
    # Strong rim: white light-gradient stroke + a soft indigo atmosphere ring.
    rim = (
        '<circle cx="512" cy="512" r="310" fill="none" stroke="url(#rim)" stroke-width="7"/>'
        '<circle cx="512" cy="512" r="320" fill="none" stroke="#6366F1" '
        'stroke-opacity="0.22" stroke-width="6"/>'
    )
    if scale != 1.0 or cx != 512 or cy != 512:
        t = f'translate({cx},{cy}) scale({scale}) translate(-512,-512)'
        body = f'<g transform="{t}">{body}</g>'
        rim = f'<g transform="{t}">{rim}</g>'
    return body + rim


def _wordmark(x: float, y: float, size: float) -> str:
    return (
        f'<text x="{x}" y="{y}" text-anchor="middle" font-family="DejaVu Sans" '
        f'font-weight="bold" font-size="{size}" letter-spacing="2" fill="url(#wm)">EmoSphere</text>'
    )


def write(name: str, w: int, h: int, body: str) -> None:
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" '
        f'viewBox="0 0 {w} {h}">{NOTE}{_defs()}{body}</svg>\n'
    )
    (OUT / name).write_text(svg)
    print(f"wrote {name}")


# 1. Master icon - Web/PWA, apple-touch, Android legacy, launcher_icons source.
write(
    "emosphere_icon.svg",
    1024,
    1024,
    '<rect width="1024" height="1024" fill="url(#bg)"/>'
    '<circle cx="512" cy="512" r="420" fill="url(#halo)"/>' + _planet(1.0),
)

# 2. Android adaptive foreground (transparent, content inside the 66% safe zone).
write(
    "emosphere_adaptive_foreground.svg",
    1024,
    1024,
    '<circle cx="512" cy="512" r="336" fill="url(#halo)"/>' + _planet(1.0),
)

# 3. Android adaptive background (full-bleed #0B1020 -> #0E1430 gradient).
write(
    "emosphere_adaptive_background.svg",
    1024,
    1024,
    '<rect width="1024" height="1024" fill="url(#bg)"/>',
)

# 4. Maskable PWA icon: content scaled into the central 80% safe circle.
write(
    "emosphere_maskable.svg",
    1024,
    1024,
    '<rect width="1024" height="1024" fill="url(#bg)"/>'
    '<circle cx="512" cy="512" r="420" fill="url(#halo)"/>' + _planet(0.86),
)

# 5. Splash hero (transparent): planet + wordmark, used by flutter_native_splash
#    and as the logo for the portrait/landscape splash screens.
write(
    "emosphere_splash_hero.svg",
    1024,
    1024,
    '<circle cx="512" cy="430" r="270" fill="url(#halo)"/>'
    + _planet(0.78, cx=512, cy=430)
    + _wordmark(512, 872, 116),
)

# 6. Splash screens, dark background + logo, portrait and landscape.
write(
    "emosphere_splash_portrait.svg",
    1080,
    2340,
    '<rect width="1080" height="2340" fill="url(#bg)"/>'
    '<circle cx="540" cy="1080" r="560" fill="url(#halo)"/>'
    + _planet(0.62, cx=540, cy=1000)
    + _wordmark(540, 1420, 108),
)
write(
    "emosphere_splash_landscape.svg",
    2340,
    1080,
    '<rect width="2340" height="1080" fill="url(#bg)"/>'
    '<circle cx="1170" cy="520" r="470" fill="url(#halo)"/>'
    + _planet(0.52, cx=1170, cy=430)
    + _wordmark(1170, 760, 96),
)
